#!/usr/bin/env python3
"""Generate the manifest signing key pair and embed the PUBLIC key into the launcher.

  python3 tools/keygen.py                # writes keys/manifest_private.pem + keys/manifest_public.pem
                                         # and regenerates src/L2Launcher.Core/PublicKey.cs
  python3 tools/keygen.py --embed-only   # re-embed an existing keys/manifest_public.pem

Keep keys/manifest_private.pem OFFLINE (not on the web server, not in git). Losing it means you must
ship a new launcher build with a new public key; leaking it lets anyone push files to your players.
"""
import argparse, os, sys
from pathlib import Path
from cryptography.hazmat.primitives.asymmetric import rsa
from cryptography.hazmat.primitives import serialization

ROOT = Path(__file__).resolve().parent.parent
CS = ROOT / "src" / "L2Launcher.Core" / "PublicKey.cs"

def embed(pub_pem: str):
    CS.write_text(
        "// GENERATED by tools/keygen.py - do not edit by hand.\n"
        "namespace L2Launcher.Core;\n\n"
        "public static class PublicKey\n{\n"
        "    /// <summary>RSA public key used to verify manifest.json.sig.</summary>\n"
        '    public const string Pem = @"' + pub_pem.strip() + '";\n}\n', encoding="utf-8")
    print(f"embedded public key -> {CS}")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--keys-dir", default=str(ROOT / "keys"))
    ap.add_argument("--bits", type=int, default=3072)
    ap.add_argument("--force", action="store_true", help="overwrite an existing private key")
    ap.add_argument("--embed-only", action="store_true")
    a = ap.parse_args()
    kd = Path(a.keys_dir); kd.mkdir(parents=True, exist_ok=True)
    priv_p, pub_p = kd / "manifest_private.pem", kd / "manifest_public.pem"
    if a.embed_only:
        embed(pub_p.read_text()); return
    if priv_p.exists() and not a.force:
        sys.exit(f"{priv_p} exists; use --force to replace it (old launchers will reject new manifests!)")
    key = rsa.generate_private_key(public_exponent=65537, key_size=a.bits)
    priv_pem = key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                 serialization.NoEncryption())
    pub_pem = key.public_key().public_bytes(serialization.Encoding.PEM,
                                            serialization.PublicFormat.SubjectPublicKeyInfo).decode()
    fd = os.open(priv_p, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as f: f.write(priv_pem)
    pub_p.write_text(pub_pem)
    print(f"private key -> {priv_p} (KEEP SECRET)\npublic key  -> {pub_p}")
    embed(pub_pem)

if __name__ == "__main__":
    main()
